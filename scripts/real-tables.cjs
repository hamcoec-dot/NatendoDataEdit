const returns = path.join(WORK, "made up returns.csv");
const roster = path.join(WORK, "made up roster.csv");
// 40 made-up precincts; row 17's total is one vote off, so the column totals do not add up by 1.
const rowsOf = Array.from({ length: 40 }, (_, i) => {
  const early = 10 + ((i * 7) % 23);
  const day = 5 + ((i * 11) % 17);
  return [`P${i + 1}`, early, day, early + day + (i === 16 ? 1 : 0)];
});
fs.writeFileSync(returns, "Precinct,Early,Day,Total\r\n" + rowsOf.map((r) => r.join(",")).join("\r\n") + "\r\n");
fs.writeFileSync(roster, "Precinct\r\n" + rowsOf.map((r) => r[0]).join("\r\n") + "\r\n");
const sumEarly = rowsOf.reduce((a, r) => a + r[1], 0);
const sumDay = rowsOf.reduce((a, r) => a + r[2], 0);
const sumTotal = rowsOf.reduce((a, r) => a + r[3], 0);
const shot = (m, n) => m.screenshot({ path: path.join(evidence, n) });
const clean = () => {
  for (const f of ["session.json", "recent.json"]) {
    const mine = path.join(DATA, f);
    if (fs.existsSync(mine) && hash(path.join(BACKUP, f)) !== null) fs.rmSync(mine);
  }
};
const text = async (m) => ((await m.locator("[role=dialog]").first().textContent().catch(() => "")) || "").replace(/\s+/g, " ");

(async () => {
  for (let i = 0; i < 120 && running(); i++) await sleep(5000);
  if (running()) {
    say("another Natendo Data Edit stayed open: nothing was touched");
    process.exit(3);
  }
  backup();
  clean();
  try {
    const m = await start([returns, roster]);
    await m.locator("[role=tab]", { hasText: "made up returns" }).first().click();
    await sleep(500);
    await cmd(m, "Table checks (row count");
    const run = m.getByRole("button", { name: "Run checks" });
    ok(!!(await waitFor(() => run.isVisible(), 5000)), "the command opens Data checks on its table checks");
    const formula = m.getByLabel("Formula");
    ok(await formula.isVisible(), "a formula table check is there to fill in");
    // Built from the "Put in" picker, as a person would, then the = typed between.
    await m.getByLabel("Put in a column's figure").selectOption("SUM:1");
    await m.getByLabel("Put in a column's figure").selectOption("SUM:2");
    let f = await formula.inputValue();
    ok(f === "SUM([Early]) SUM([Day])", `the picker puts in figures with the column titles: ${f}`);
    await formula.fill("SUM([Early]) + SUM([Day]) = SUM([Total])");
    await m.getByRole("button", { name: "Add a table check" }).click();
    await m.getByLabel("Table check", { exact: true }).nth(1).selectOption("row_count_same_as");
    await m.getByLabel("File with as many rows").selectOption("made up roster.csv");
    await shot(m, "tables-dialog.png");
    await run.click();
    await sleep(1500);
    let t = await text(m);
    const want = `SUM([Total]): failed: ${sumEarly + sumDay} (wanted = ${sumTotal} (within 0.005))`;
    ok(t.includes(want), `the totals do not add up, by the figures made here (${want}): ${t.slice(t.indexOf("Table check 1"), t.indexOf("Table check 1") + 140)}`);
    ok(t.includes("As many rows as made up roster.csv: passed: 40 rows"), "as many rows as the roster: passed");
    await shot(m, "tables-run.png");
    // One vote in 1,500 is within 1%.
    await m.getByLabel("Tolerance kind").selectOption("relative");
    await m.getByLabel("Tolerance", { exact: true }).fill("1");
    await run.click();
    await sleep(1500);
    t = await text(m);
    ok(t.includes(`passed: ${sumEarly + sumDay}.`), `within 1% it passes: ${t.slice(t.indexOf("Table check 1"), t.indexOf("Table check 1") + 120)}`);
    await shot(m, "tables-within.png");
    // Keep and close; then close the roster: Check now says the check did not run.
    await m.getByRole("button", { name: "Keep and close" }).click();
    await sleep(500);
    await m.locator("[role=tab]", { hasText: "made up roster" }).first().click();
    await sleep(400);
    await m.keyboard.press("Escape");
    await m.keyboard.press("Control+w");
    await sleep(1000);
    await m.locator("[role=tab]", { hasText: "made up returns" }).first().click();
    await sleep(400);
    await cmd(m, "Check the whole table now");
    await sleep(1500);
    const said = await msg(m);
    ok(said.includes("did not pass") && said.includes("open made up roster.csv"), `Check now says the table check did not run: ${said}`);
    const status = ((await m.locator("footer.status").textContent().catch(() => "")) || "").replace(/\s+/g, " ");
    ok(status.includes("1 table check not passed"), `the status bar counts it: ${status.slice(0, 200)}`);
    await shot(m, "tables-not-run.png");
  } catch (e) {
    ok(false, String(e && e.stack ? e.stack : e));
  } finally {
    await killApp();
    restore();
    say(failed ? `${failed} FAILED` : "all passed");
    process.exit(failed ? 1 : 0);
  }
})();
