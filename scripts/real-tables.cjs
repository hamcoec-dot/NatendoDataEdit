// Drives the REAL built app over table checks: made-up precinct returns whose Early + Day columns should add up
// to Total (one row is a vote off) and a made-up roster open in another tab. The table checks are made from
// command search (the formula built with the dialog's picker), run, compared with figures worked out here,
// passed within a 1% tolerance, kept; then the roster is closed and Check now says that check did not run.
//
// Usage: NODE_PATH=<folder with playwright> node scripts/real-tables.cjs <exe> <evidence folder>
// The app's own data is backed up and put back.

