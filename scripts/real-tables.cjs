const crypto = require("crypto");

const [exe, evidence, which = "all"] = process.argv.slice(2);
if (!exe || !evidence) {
  console.log("usage: node scripts/real-tables.cjs <exe> <evidence folder> [scenarios]");
  process.exit(2);
}
